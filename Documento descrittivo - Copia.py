# Barbieri e clienti usano la stessa app scaricata dal Play Store. 

# App Barbieri:
# L'app avrà 4 sezioni prinicipali:
# 	- Prenotazioni:
# 		- Attive: Prenotazioni filtrate per per data(quella in cui avviene il servizio) (possibile filtrare anche per nome e cognome)
# 	 	- Storico: Prenotazioni passate filtrate per data (possibile filtrare anche per nome e cognome)
	
# 	- Profilo: Nel profilo saranno presenti :
# 		-Impostazioni: dove sarà possibile cambiare password(*), eliminare l'account(), logout, visualizzare le faq(*), Informazioni profilo (nome, cognome e altre informazioni), Abbonamento(*)
# 			* Popup con presente "vechia password" "nuova password" "conferma nuova password"
# 			* Popup con presente "sei sicuro di voler eliminare l'account?" (con bottone "si" e "no")
# 			* Se si aprono le faq, ci saranno una 10 di domande (versione barbiere)
# 			* Popup che dice se l'abbonamento è presente(in caso quando è stato acquistato e quando scade) o assente(in caso bottone "abbonati ora)
	
# 	- Catalogo Prodotti: Possibiltà di inserire nuovi prodotti o modificare quelli presenti
# 	- Servizi: Possibilità di inserire nuovi servizi o modificare quelli presenti

# App Clienti:  
# L'app avrà 4 sezioni principali:

# - Home:  
# 	- Visualizzazione delle prenotazioni attive  
# 	- Possibilità di tornare indietro per selezionare il barbiere preferito  
# 	- Messaggio di benvenuto ("Ciao utente") e nome del parrucchiere preferito  

# - Prenota:  
# 	- Seleziona i servizi preferiti tra quelli elencati
# 		- Calendario con la possibilità di selezionare un giorno e vedere le date disponibili*
# 			- Visualizzazione degli orari disponibili per il giorno selezionato
	
# - Catalogo Prodotti:  
# 	- Lista dei prodotti venduti dal parrucchiere (Visualizzazione immagine accanto a ogni prodotto):  
# 		- Attrezzi (es. phon, piastre per capelli, rasoi)  
# 		- Prodotti per capelli (es. gel, lacche, cere, shampoo, balsamo)  
# 		- Profumi   
	 
# - Profilo:  
# 	- Impostazioni:
# 		- Informazioni profilo: 
# 			nome, cognome e altre informazioni  
# 		- Cambiare password  
# 		- Visualizzare le FAQ(*) 
# 		- Logout
# 		- Eliminare l’account  
# 	*Eccezione: qualora non si fosse selezionato ancora il barbiere preferito:*  
# 	- Visualizza la scritta "Ciao user" e il bottone "Seleziona il tuo barbiere preferito"(*)
# 		* Ti porta alla pagina di selezione del barbiere preferito (selezionabile tramite mappa o tramite ricerca)

# *Note generali:*  
# - Al momento non sono previsti pagamenti in app  
# - È possibile solo la **visualizzazione dei prezzi**, non l’acquisto diretto  
# - È possibile prenotare un prodotto e pagarlo **in loco**  
# - Il pagamento dell’abbonamento sarà possibile **solo da sito web** (anche versione mobile)
